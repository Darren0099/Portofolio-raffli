let currentLang = "id";
let roleIndex = 0;
let charIndex = 0;
let isDeleting = false;
let typewriterTimeout = null;

const typewriterElement = document.getElementById("typewriter");

function typeEffect() {
  const activeRoles = translations[currentLang].roles;
  const currentRole = activeRoles[roleIndex % activeRoles.length];
  
  if (isDeleting) {
    typewriterElement.textContent = currentRole.substring(0, charIndex - 1);
    charIndex--;
  } else {
    typewriterElement.textContent = currentRole.substring(0, charIndex + 1);
    charIndex++;
  }

  let typeSpeed = isDeleting ? 40 : 80;

  if (!isDeleting && charIndex === currentRole.length) {
    typeSpeed = 2000;
    isDeleting = true;
  } else if (isDeleting && charIndex === 0) {
    isDeleting = false;
    roleIndex = (roleIndex + 1) % activeRoles.length;
    typeSpeed = 400;
  }

  typewriterTimeout = setTimeout(typeEffect, typeSpeed);
}

function updateLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];

  const navs = document.querySelectorAll(".nav-item");
  if (navs.length >= 5) {
    navs[0].innerHTML = `<span class="dot"></span> ${t.navProfile}`;
    navs[1].innerHTML = `<span class="dot"></span> ${t.navSkills}`;
    navs[2].innerHTML = `<span class="dot"></span> ${t.navExperience}`;
    navs[3].innerHTML = `<span class="dot"></span> ${t.navProjects}`;
    navs[4].innerHTML = `<span class="dot"></span> ${t.navContact}`;
  }

  const greetingBadge = document.querySelector(".greeting-badge span");
  if (greetingBadge) greetingBadge.textContent = t.greeting;

  const heroDesc = document.querySelector(".hero-description");
  if (heroDesc) heroDesc.textContent = t.heroDesc;

  const btnPortfolio = document.querySelector(".btn-primary");
  if (btnPortfolio) {
    btnPortfolio.childNodes[0].nodeValue = t.btnPortfolio + " ";
  }

  const btnCv = document.querySelector(".btn-outline");
  if (btnCv) btnCv.textContent = t.btnCv;

  const badgeCvText = document.querySelector("#circlePath + text textPath");
  if (badgeCvText) badgeCvText.textContent = t.badgeCv;

  const skillsTitle = document.querySelector(".skills-title");
  if (skillsTitle) skillsTitle.textContent = t.skillsTitle;

  const skillsDescs = document.querySelectorAll(".skills-desc");
  if (skillsDescs.length >= 2) {
    skillsDescs[0].innerHTML = t.skillsDesc1;
    skillsDescs[1].innerHTML = t.skillsDesc2;
  }

  const statSubText = document.querySelectorAll(".stat-sub");
  if (statSubText.length >= 2) {
    statSubText[1].textContent = t.statProjects;
  }

  const expTitle = document.querySelector(".exp-title");
  if (expTitle) expTitle.textContent = t.expTitle;

  const expDesc = document.querySelector(".exp-desc");
  if (expDesc) expDesc.textContent = t.expDesc;

  const roadmapCards = document.querySelectorAll(".roadmap-card");
  roadmapCards.forEach((card, index) => {
    if (t.expList[index]) {
      const badge = card.querySelector(".role-badge");
      const title = card.querySelector("h3");
      const desc = card.querySelector("p");

      if (badge) badge.textContent = t.expList[index].badge;
      if (title) title.textContent = t.expList[index].title;
      if (desc) desc.textContent = t.expList[index].desc;
    }
  });

  clearTimeout(typewriterTimeout);
  charIndex = 0;
  isDeleting = false;
  typeEffect();
}

document.addEventListener("DOMContentLoaded", () => {
  typeEffect();

  const langToggle = document.getElementById("langToggle");
  if (langToggle) {
    langToggle.addEventListener("click", () => {
      langToggle.classList.toggle("en");
      const isEnglish = langToggle.classList.contains("en");
      updateLanguage(isEnglish ? "en" : "id");
    });
  }

  const navLinks = document.querySelectorAll(".nav-item");
  navLinks.forEach(link => {
    link.addEventListener("click", function (e) {
      e.preventDefault();
      const targetId = this.getAttribute("href");
      const targetSection = document.querySelector(targetId);

      if (targetSection) {
        targetSection.scrollIntoView({
          behavior: "smooth",
          block: "start"
        });
      }
    });
  });

  const sections = document.querySelectorAll("section[id]");
  window.addEventListener("scroll", () => {
    let currentScroll = window.scrollY;

    sections.forEach(section => {
      const sectionTop = section.offsetTop - 120;
      const sectionHeight = section.offsetHeight;
      const sectionId = section.getAttribute("id");

      if (currentScroll >= sectionTop && currentScroll < sectionTop + sectionHeight) {
        navLinks.forEach(item => {
          item.classList.remove("active");
          if (item.getAttribute("href") === "#" + sectionId) {
            item.classList.add("active");
          }
        });
      }
    });
  });

  const roadmapItems = document.querySelectorAll(".roadmap-item");
  const observerOptions = {
    threshold: 0.15
  };

  const roadmapObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("show");
        observer.unobserve(entry.target);
      }
    });
  }, observerOptions);

  roadmapItems.forEach(item => {
    roadmapObserver.observe(item);
  });
});
